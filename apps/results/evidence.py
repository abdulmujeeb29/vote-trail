"""Deterministic evidence pack: same inputs → byte-identical ZIP."""

from __future__ import annotations

import html
import io
import json
import zipfile
from typing import Any

from apps.core.models import AuditLog
from apps.elections.models import Election
from apps.geo.models import PollingUnit

from .models import IrevSheet, ResultCheck, ResultUpload

_EPOCH = (1980, 1, 1, 0, 0, 0)


def _dump(obj: Any) -> bytes:
    return json.dumps(obj, sort_keys=True, indent=2, default=str).encode()


def _add(zf: zipfile.ZipFile, name: str, data: bytes) -> None:
    info = zipfile.ZipInfo(name, date_time=_EPOCH)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    zf.writestr(info, data)


def build_pack(election: Election, pu: PollingUnit) -> bytes:
    checks = list(
        ResultCheck.objects.filter(election=election, polling_unit=pu).order_by("revision")
    )
    uploads = list(
        ResultUpload.objects.filter(election=election, polling_unit=pu)
        .select_related("extraction", "participant")
        .order_by("pk")
    )
    irev = (
        IrevSheet.objects.filter(election=election, polling_unit=pu)
        .select_related("extraction")
        .first()
    )
    files: dict[str, bytes] = {}
    upload_meta = []
    for u in uploads:
        meta = {
            "id": u.pk,
            "source": u.source,
            "sha256": u.sha256,
            "captured_at": u.captured_at,
            "received_at": u.received_at,
            "location": [u.lat, u.lng] if u.lat is not None else None,
            "flags": u.flags,
            "state": u.state,
            "role": u.participant.role if u.participant else "voter",
            "party": u.participant.party if u.participant else "",
            "figures": u.extraction.figures if u.extraction else u.sms_figures,
            "low_confidence": u.extraction.low_confidence_fields if u.extraction else [],
            "demo": u.is_demo,
        }
        upload_meta.append(meta)
        files[f"uploads/{u.pk}.json"] = _dump(meta)
        if u.image:
            with u.image.open("rb") as fh:
                files[f"uploads/{u.pk}.jpg"] = fh.read()
    irev_meta = None
    if irev is not None:
        irev_meta = {
            "source_url": irev.source_url,
            "uploaded_at": irev.uploaded_at,
            "sha256": irev.sha256,
            "mock": irev.is_mock,
            "figures": irev.extraction.figures if irev.extraction else None,
        }
        files["irev/irev.json"] = _dump(irev_meta)
        if irev.image:
            with irev.image.open("rb") as fh:
                files["irev/irev.jpg"] = fh.read()
    history = [
        {
            "revision": c.revision,
            "status": c.status,
            "reasons": c.reasons,
            "origin_count": c.origin_count,
            "cross_party": c.cross_party,
            "diffs": c.diffs,
            "created_at": c.created_at,
        }
        for c in checks
    ]
    files["history.json"] = _dump(history)
    object_ids = [("results.resultupload", str(u.pk)) for u in uploads] + [
        ("results.resultcheck", str(c.pk)) for c in checks
    ]
    audit = [
        {
            "at": a.created_at,
            "actor": a.actor,
            "action": a.action,
            "object": f"{a.object_type}:{a.object_id}",
            "after_digest": a.after_digest,
        }
        for a in AuditLog.objects.order_by("created_at", "id")
        if (a.object_type, a.object_id) in set(object_ids)
    ]
    files["audit.json"] = _dump(audit)
    latest = checks[-1] if checks else None
    manifest = {
        "election": election.name,
        "polling_unit": {"code": pu.code, "name": pu.name},
        "status": latest.status if latest else "pending",
        "revision": latest.revision if latest else 0,
        "files": {name: _sha(data) for name, data in sorted(files.items())},
        "note": "Generated by VoteTrail. VoteTrail never declares results; only INEC does.",
    }
    files["manifest.json"] = _dump(manifest)
    files["summary.html"] = _summary(pu, election, latest, upload_meta, irev_meta).encode()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name in sorted(files):
            _add(zf, name, files[name])
    return buf.getvalue()


def _sha(data: bytes) -> str:
    import hashlib

    return hashlib.sha256(data).hexdigest()


def _summary(pu, election, latest, uploads, irev) -> str:
    esc = html.escape
    rows = "".join(
        "<tr>"
        f"<td>{u['id']}</td><td>{esc(str(u['role']))}</td><td>{esc(str(u['captured_at']))}</td>"
        f"<td>{esc(json.dumps(u['figures'], sort_keys=True))}</td>"
        f"<td>{esc(str(u['state']))}</td></tr>"
        for u in uploads
    )
    status = esc(latest.status if latest else "pending")
    return (
        "<!doctype html><meta charset=utf-8><title>Evidence pack</title>"
        f"<h1>Evidence pack: PU {esc(pu.code)}</h1><p>{esc(pu.name)} · {esc(election.name)}</p>"
        f"<p>Status: <strong>{status}</strong></p>"
        "<table border=1 cellpadding=4><tr><th>Upload</th><th>Role</th><th>Captured</th>"
        f"<th>Figures</th><th>State</th></tr>{rows}</table>"
        f"<h2>IReV</h2><pre>{esc(json.dumps(irev, sort_keys=True, default=str, indent=2))}</pre>"
        "<p>VoteTrail never declares results. Only INEC declares results.</p>"
    )
